        self.assertEqual(go["assertions"], 9)
        self.assertEqual(go["assertions_per_100_test_loc"], 90.0)
        self.assertEqual(go["go_tool_statement_coverage_pct"], 80.0)
        self.assertEqual(go["covered_pct_of_coverable_loc"], 80.0)
        self.assertEqual(web["test_loc"], 10)
        self.assertEqual(web["covered_prod_loc"], 2)
        self.assertEqual(web["density"], 5.0)
        self.assertEqual(web["assertions_per_100_test_loc"], 100.0)
        # Sum of lines, not the average of the two densities (that would be 3.75).
        self.assertEqual(without_local["overall_unit"]["test_loc"], 20)
        self.assertEqual(without_local["overall_unit"]["covered_prod_loc"], 6)
        self.assertEqual(without_local["overall_unit"]["density"], 3.333)

        self.assertEqual(with_local["go"]["density"], go["density"])
        self.assertEqual(with_local["go"]["covered_prod_loc"], go["covered_prod_loc"])
        self.assertEqual(with_local["overall_unit"]["density"], 3.333)
        self.assertEqual(with_local["go"]["covered_elsewhere_loc"], 3)
        self.assertNotIn("covered_elsewhere_loc", without_local["go"])

