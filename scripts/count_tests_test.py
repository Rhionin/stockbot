    def test_flag_a_uses_strict_thresholds(self) -> None:
        cases = (
            ("go at 5.2", 152, 50, 100, 40, [], 5.2),
            ("go above 5.2", 153, 50, 100, 40, ["go"], 5.3),
            ("web at 6.3", 100, 40, 163, 50, [], 6.3),
            ("web above 6.3", 100, 40, 164, 50, ["web_unit"], 6.4),
            ("coverage shrinks", 200, 30, 100, 40, [], None),
            ("coverage unchanged", 180, 40, 100, 40, [], None),
        )
        for name, go_test, go_covered, web_test, web_covered, fired, marginal in cases:
            with self.subTest(name):
                base, head, base_repo, head_repo = self.pair(
                    go_test=100, go_covered=40, web_test=100, web_covered=40
                )
                head_path = self.dump(
                    "head",
                    go_test=go_test,
                    go_covered=go_covered,
                    web_test=web_test,
                    web_covered=web_covered,
                )
                diff, markdown, _stdout = load_diff(
                    base,
                    head_path,
                    "--base-repo",
                    str(base_repo.root),
                    "--head-repo",
                    str(head_repo.root),
                )
                self.assertEqual(diff["flag_a"]["fired"], bool(fired))
                self.assertEqual(diff["flag_a"]["languages"], fired)
                language = "web_unit" if "web" in name else "go"
                self.assertEqual(diff["languages"][language]["marginal_density"], marginal)
                self.assertFalse(diff["flag_b"]["implemented"])
                self.assertIn("gremlins", diff["flag_b"]["todo"])
                self.assertIn("Stryker", diff["flag_b"]["todo"])
                self.assertIn("<!-- stockbot-test-metrics -->", markdown)
                self.assertIn("does not block merge", markdown)
                self.assertIn("Go > 5.2, web > 6.3", markdown)
                if fired:
                    self.assertIn("marginal density is", markdown)
                else:
                    self.assertIn("Not fired.", markdown.split("**Flag C")[0])

