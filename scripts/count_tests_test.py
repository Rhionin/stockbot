#!/usr/bin/env python3
"""Behavior tests for scripts/count-tests.py.

Fixtures are tiny trees and cover profiles. The tests check the counting rules,
the exclusions, and the diff math a pull request comment is built from.
"""

import json
import os
import subprocess
import sys
import tempfile
import textwrap
import unittest
from pathlib import Path

SCRIPT = Path(__file__).resolve().parent / "count-tests.py"


def write(root: Path, rel: str, text: str) -> None:
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def run(*args: str) -> subprocess.CompletedProcess[str]:
    env = os.environ.copy()
    # Keep `git rev-parse` from walking out of a fixture into this checkout.
    env["GIT_CEILING_DIRECTORIES"] = tempfile.gettempdir()
    return subprocess.run(
        [sys.executable, str(SCRIPT), *args],
        capture_output=True,
        text=True,
        env=env,
        check=False,
    )


def load_report(*args: str) -> dict:
    with tempfile.TemporaryDirectory() as tmp:
        destination = str(Path(tmp) / "report.json")
        proc = run(*args, "--json", destination)
        if proc.returncode != 0:
            raise AssertionError(f"{proc.args}\n{proc.stderr}\n{proc.stdout}")
        return json.loads(Path(destination).read_text())


def load_diff(*args: str) -> tuple[dict, str, str]:
    with tempfile.TemporaryDirectory() as tmp:
        destination = str(Path(tmp) / "diff.json")
        markdown = str(Path(tmp) / "comment.md")
        proc = run("diff", *args, "--json", destination, "--markdown", markdown)
        if proc.returncode != 0:
            raise AssertionError(f"{proc.args}\n{proc.stderr}\n{proc.stdout}")
        return json.loads(Path(destination).read_text()), Path(markdown).read_text(), proc.stdout


class Repo:
    def __init__(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        self.root = Path(self._tmp.name)

    def close(self) -> None:
        self._tmp.cleanup()

    def write(self, rel: str, text: str) -> None:
        write(self.root, rel, text)

    def report(self, **paths: str) -> dict:
        args = ["report", "--repo", str(self.root)]
        for flag, path in paths.items():
            args.extend(["--" + flag.replace("_", "-"), path])
        return load_report(*args)


class CountTestsTest(unittest.TestCase):
    def setUp(self) -> None:
        self.repos: list[Repo] = []

    def tearDown(self) -> None:
        for repo in self.repos:
            repo.close()

    def repo(self) -> Repo:
        created = Repo()
        self.repos.append(created)
        return created

    def test_code_lines_skip_blanks_comments_and_keep_trailing_comments(self) -> None:
        repo = self.repo()
        repo.write(
            "p.go",
            "\n".join(
                [
                    "package p",
                    "",
                    "// whole line comment",
                    "func F() int {",
                    '\ts := "// not a comment"',
                    "\t/* only a block",
                    "\t   still a block */",
                    "\treturn 1 // trailing comment counts",
                    "}",
                    "var x = 1 /* inline */ + 2",
                    "",
                ]
            ),
        )
        report = repo.report()
        self.assertEqual(report["go"]["files"]["p.go"]["code_lines"], [1, 4, 5, 8, 9, 10])
        self.assertEqual(report["go"]["prod_loc"], 6)

    def test_raw_string_continuation_stays_on_the_v1_baseline_rule(self) -> None:
        # A later line is scanned on its own. Changing that moves the baseline.
        repo = self.repo()
        repo.write(
            "p.go",
            "\n".join(
                [
                    "package p",
                    "",
                    "var s = `",
                    "// looks like a comment",
                    "`",
                    "",
                ]
            ),
        )
        report = repo.report()
        self.assertEqual(report["go"]["files"]["p.go"]["code_lines"], [1, 3, 5])

